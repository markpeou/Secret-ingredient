/*
 * Scoring engine. Pure functions, no DOM.
 *
 * Pipeline:
 *   answers -> dimension profile -> spice affinities
 *           -> dish (the one whose real spice set best fits those affinities)
 *           -> blend built only from that dish's spices, proportions tilted by the answers
 *           -> integer percentages (always exactly 100)
 *
 * Because the blend is drawn from the dish's own spices, every result makes
 * culinary sense. Deterministic: the same answer set always gives the same result.
 */
(function (SI) {
  const TUNING = {
    smoothing: 0.75,  // added to raw + opportunity so one answer can't dominate
    tilt: 1.1,        // how far answers can shift a dish's usual proportions
    maxSpices: 6,     // most spices shown in one blend
    minSpices: 3,     // fewest spices in one blend
    step: 5,          // percentages are multiples of 5 (a recipe, not a measurement)
    minPct: 10,       // every spice in the blend gets at least this much
    lowSpread: 0.34   // profile spread below this counts as "balanced"
  };
  SI.TUNING = TUNING;

  const byId = (list) => Object.fromEntries(list.map((x) => [x.id, x]));

  function vecNorm(v) {
    return Math.sqrt(Object.values(v).reduce((a, b) => a + b * b, 0));
  }
  function cosine(a, b) {
    let dot = 0;
    for (const k in a) if (b[k]) dot += a[k] * b[k];
    const n = vecNorm(a) * vecNorm(b);
    return n ? dot / n : 0;
  }

  /*
   * 1. Profile. For each dimension we compare what the participant chose
   * against what was on offer in the questions they saw ("opportunity").
   * Affinity ~1 means average, >1 means the participant leaned into it.
   * This keeps random question selection from skewing results.
   */
  function buildProfile(answers) {
    const qById = byId(SI.QUESTIONS);
    const raw = {}, opp = {};
    SI.DIMENSIONS.forEach((d) => { raw[d] = 0; opp[d] = 0; });

    const resolved = [];
    // Canonical order (question bank order) so the same answer set always scores identically.
    const order = Object.fromEntries(SI.QUESTIONS.map((q, i) => [q.id, i]));
    const canonical = answers.slice().sort((a, b) => (order[a.questionId] ?? 1e9) - (order[b.questionId] ?? 1e9));
    canonical.forEach(({ questionId, optionIndex }) => {
      const q = qById[questionId];
      if (!q) throw new Error('Unknown question: ' + questionId);
      const opt = q.options[optionIndex];
      if (!opt) throw new Error('Unknown option ' + optionIndex + ' for ' + questionId);
      resolved.push({ question: q, option: opt, optionIndex });
      SI.DIMENSIONS.forEach((d) => {
        raw[d] += opt.s[d] || 0;
        opp[d] += q.options.reduce((sum, o) => sum + (o.s[d] || 0), 0) / q.options.length;
      });
    });

    const affinity = {};
    SI.DIMENSIONS.forEach((d) => {
      affinity[d] = (raw[d] + TUNING.smoothing) / (opp[d] + TUNING.smoothing);
    });

    const vals = Object.values(affinity);
    const mean = vals.reduce((a, b) => a + b, 0) / vals.length;
    const spread = Math.sqrt(vals.reduce((a, b) => a + (b - mean) ** 2, 0) / vals.length);
    const ranked = SI.DIMENSIONS.slice().sort((a, b) => affinity[b] - affinity[a] || SI.DIMENSIONS.indexOf(a) - SI.DIMENSIONS.indexOf(b));

    return { raw, opp, affinity, mean, spread, ranked, resolved, balanced: spread < TUNING.lowSpread };
  }

  /* 2. Spice scores: weighted average of the affinities a spice expresses. */
  function scoreSpices(profile) {
    return SI.SPICES.map((spice, order) => {
      let num = 0, den = 0;
      for (const d in spice.vector) {
        num += spice.vector[d] * profile.affinity[d];
        den += spice.vector[d];
      }
      return { spice, order, score: num / den };
    }).sort((a, b) => b.score - a.score || a.order - b.order);
  }

  /*
   * Standardised spice affinities: how much more (or less) this player leans towards
   * each spice than a typical player does. SI.SPICE_NORMS (generated by
   * scripts/calibrate.js from simulated players) holds each spice's typical mean and
   * spread; without it, spices are compared within the player's own scores.
   */
  function centre(scored) {
    const norms = SI.SPICE_NORMS;
    if (norms) return Object.fromEntries(scored.map((x) => {
      const n = norms[x.spice.id] || { mean: 1, sd: 0.25 };
      return [x.spice.id, (x.score - n.mean) / (n.sd || 1)];
    }));
    const vals = scored.map((x) => x.score);
    const mean = vals.reduce((a, b) => a + b, 0) / vals.length;
    const sd = Math.sqrt(vals.reduce((a, b) => a + (b - mean) ** 2, 0) / vals.length) || 1;
    return Object.fromEntries(scored.map((x) => [x.spice.id, (x.score - mean) / sd]));
  }

  /*
   * 3. Dish. Each dish is scored by how well its real spice set lines up with the
   * player's spice affinities (a projection onto the dish's normalised spice
   * weights), plus a small calibration offset that keeps every dish reachable.
   */
  function chooseDish(centred, bias = SI.DISH_BIAS || {}) {
    const ranked = SI.DISHES.map((dish, order) => {
      const w = dish.spices;
      let dot = 0, norm = 0;
      for (const id in w) { dot += w[id] * (centred[id] || 0); norm += w[id] * w[id]; }
      return { dish, order, score: dot / Math.sqrt(norm) + (bias[dish.id] || 0) };
    }).sort((a, b) => b.score - a.score || a.order - b.order);
    return { dish: ranked[0].dish, ranked };
  }

  /* 4. Blend: the dish's own spices, reweighted towards the ones this player leans into. */
  function composeBlend(dish, centred) {
    const spiceById = byId(SI.SPICES);
    const items = Object.entries(dish.spices).map(([id, w]) => ({
      spice: spiceById[id],
      order: SI.SPICES.findIndex((sp) => sp.id === id),
      weight: w * Math.exp(TUNING.tilt * (centred[id] || 0))
    })).sort((a, b) => b.weight - a.weight || a.order - b.order);
    return allocatePercentages(items.slice(0, Math.max(TUNING.minSpices, Math.min(TUNING.maxSpices, items.length))));
  }

  /*
   * 5. Integer percentages that always total exactly 100.
   * Each spice gets the minimum, then the rest is shared out in steps of 5
   * by the largest-remainder method. Ties break by weight, then spice order.
   */
  function allocatePercentages(picked) {
    const step = TUNING.step;
    const totalUnits = 100 / step;
    const minUnits = Math.min(TUNING.minPct / step, Math.floor(totalUnits / picked.length));
    const weights = picked.map((p) => Math.max(p.weight, 1e-6));
    const wSum = weights.reduce((a, b) => a + b, 0);
    const free = totalUnits - minUnits * picked.length;

    const exact = weights.map((w) => (w / wSum) * free);
    const units = exact.map((x) => Math.floor(x));
    let left = free - units.reduce((a, b) => a + b, 0);
    const order = exact
      .map((x, i) => ({ i, rem: x - Math.floor(x) }))
      .sort((a, b) => b.rem - a.rem || picked[b.i].weight - picked[a.i].weight || picked[a.i].order - picked[b.i].order);
    for (let k = 0; left > 0; k = (k + 1) % order.length, left--) units[order[k].i] += 1;

    return picked
      .map((p, i) => ({ ...p, pct: (units[i] + minUnits) * step }))
      .sort((a, b) => b.pct - a.pct || b.weight - a.weight || a.order - b.order);
  }

  function interpret(answers) {
    if (!answers || !answers.length) throw new Error('No answers to interpret');
    const profile = buildProfile(answers);
    const scored = scoreSpices(profile);
    const centred = centre(scored);
    const { dish, ranked } = chooseDish(centred);
    const blend = composeBlend(dish, centred);
    const result = { profile, spiceScores: scored, blend, dish, dishRanking: ranked };
    result.text = SI.narrative.compose(result);
    return result;
  }

  /* Content checks, used by tests and logged at boot. */
  function validateContent() {
    const errors = [];
    const dims = new Set(SI.DIMENSIONS);
    const spiceIds = new Set(SI.SPICES.map((s) => s.id));
    const qIds = new Set();
    SI.QUESTIONS.forEach((q) => {
      if (qIds.has(q.id)) errors.push('Duplicate question id ' + q.id);
      qIds.add(q.id);
      if (!q.options || q.options.length < 2) errors.push(q.id + ' needs at least 2 options');
      (q.options || []).forEach((o, i) => {
        const keys = Object.keys(o.s || {});
        if (!keys.length) errors.push(q.id + '[' + i + '] has no signals');
        keys.forEach((k) => {
          if (!dims.has(k)) errors.push(q.id + '[' + i + '] unknown dimension ' + k);
          if (!(o.s[k] > 0)) errors.push(q.id + '[' + i + '] non-positive weight for ' + k);
        });
      });
    });
    if (SI.QUESTIONS.length < SI.QUESTIONS_PER_SESSION) errors.push('Question bank smaller than session length');
    SI.SPICES.forEach((s) => Object.keys(s.vector).forEach((k) => { if (!dims.has(k)) errors.push(s.id + ' unknown dimension ' + k); }));
    SI.DISHES.forEach((d) => {
      const ids = Object.keys(d.spices || {});
      if (ids.length < TUNING.minSpices) errors.push(d.id + ' needs at least ' + TUNING.minSpices + ' spices');
      ids.forEach((k) => { if (!spiceIds.has(k)) errors.push(d.id + ' unknown spice ' + k); });
      const total = ids.reduce((a, k) => a + d.spices[k], 0);
      if (Math.abs(total - 1) > 0.02) errors.push(d.id + ' spice weights sum to ' + total.toFixed(2));
      if (!d.origin) errors.push(d.id + ' needs an origin');
    });
    SI.SPICES.forEach((sp) => { if (!SI.DISHES.some((d) => d.spices[sp.id])) errors.push(sp.id + ' is not used by any dish'); });
    return errors;
  }

  /* Pick n distinct questions. `random` is injectable for tests. */
  function selectQuestions(n = SI.QUESTIONS_PER_SESSION, random = Math.random) {
    const pool = SI.QUESTIONS.slice();
    for (let i = pool.length - 1; i > 0; i--) {
      const j = Math.floor(random() * (i + 1));
      [pool[i], pool[j]] = [pool[j], pool[i]];
    }
    return pool.slice(0, Math.min(n, pool.length));
  }

  SI.engine = { buildProfile, scoreSpices, centre, chooseDish, composeBlend, allocatePercentages, interpret, validateContent, selectQuestions, cosine };
})(globalThis.SI = globalThis.SI || {});
