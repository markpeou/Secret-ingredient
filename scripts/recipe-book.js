// Writes docs/recipe-book.md: a readable map of how answers feed spices, and how
// spices feed dishes. Regenerate after editing questions, spices or dishes:
//   node scripts/recipe-book.js
const fs = require('fs');
const path = require('path');
const SI = require('../tests/load');
const { players } = require('../tests/players');

const DIM = {
  explore: 'Curiosity & novelty', energy: 'Energy & action', steady: 'Stability & practicality',
  warmth: 'Warmth & connection', space: 'Independence & space', observe: 'Noticing & reflecting',
  drive: 'Determination & intensity', flow: 'Adaptability & spontaneity', play: 'Playfulness & fun'
};

const counts = {};
const sample = players(6000, 7);
sample.forEach((a) => { const r = SI.engine.interpret(a); counts[r.dish.id] = (counts[r.dish.id] || 0) + 1; });

const L = [];
L.push('# The Secret Ingredient — Recipe book', '');
L.push('Generated by `node scripts/recipe-book.js` from the game data. Edit the data files, not this document.', '');
L.push('## How it fits together', '');
L.push('1. **Answers → traits.** Each answer quietly adds weight to nine hidden traits (below). Nothing on screen names them.');
L.push('2. **Traits → spices.** Each spice expresses a few traits. A player’s affinity for a spice is how strongly they lean into those traits, compared with a typical player.');
L.push('3. **Spices → dish.** Every dish lists its real spices with rough proportions. The dish chosen is the one whose spice set best matches the player’s spice affinities.');
L.push('4. **Dish → blend.** The blend is built **only from that dish’s spices**. The dish’s usual proportions are tilted towards the spices the player leans into, then rounded to 5% steps that always total 100%.');
L.push('', 'So the blend always makes culinary sense for the dish, and two people with the same dish can still get different mixes.', '');

L.push('## Hidden traits', '');
L.push('| Trait | What it captures | Questions that feed it |', '|---|---|---|');
SI.DIMENSIONS.forEach((d) => {
  const qs = SI.QUESTIONS.filter((q) => q.options.some((o) => o.s[d])).length;
  L.push(`| \`${d}\` | ${DIM[d]} | ${qs} of ${SI.QUESTIONS.length} |`);
});
L.push('');

L.push('## Spices', '');
Object.entries(SI.SPICE_FAMILIES).forEach(([fam, label]) => {
  L.push(`### ${label}`, '');
  L.push('| Spice | Traits it expresses | Personality | Found in |', '|---|---|---|---|');
  SI.SPICES.filter((s) => s.family === fam).forEach((s) => {
    const traits = Object.entries(s.vector).sort((a, b) => b[1] - a[1]).map(([d, w]) => `${DIM[d]} ×${w}`).join(', ');
    const dishes = SI.DISHES.filter((d) => d.spices[s.id]).map((d) => d.name).join(', ');
    L.push(`| **${s.name}** | ${traits} | ${s.essence} | ${dishes} |`);
  });
  L.push('');
});

L.push('## Dishes', '');
L.push('Share of players is from 6,000 simulated players. Offset is the small calibration nudge from `scripts/calibrate.js` that keeps every dish reachable.', '');
L.push('| Dish | From | Real spice set (usual share) | Share of players | Offset |', '|---|---|---|---|---|');
SI.DISHES.forEach((d) => {
  const sp = Object.entries(d.spices).sort((a, b) => b[1] - a[1]).map(([id, w]) => `${SI.SPICES.find((s) => s.id === id).name} ${Math.round(w * 100)}%`).join(', ');
  L.push(`| **${d.name}** | ${d.origin} | ${sp} | ${(100 * (counts[d.id] || 0) / sample.length).toFixed(1)}% | ${(SI.DISH_BIAS[d.id] || 0).toFixed(2)} |`);
});
L.push('');
L.push('## Editing checklist', '');
L.push('- Add a spice to `js/data/spices.js`, draw it in `js/ui/characters.js`, and use it in at least one dish.');
L.push('- Add a dish to `js/data/dishes.js` with only spices that genuinely belong in it (weights sum to 1), and give it art in `js/ui/art.js`.');
L.push('- Run `node scripts/calibrate.js`, then `npm test`, then `node scripts/recipe-book.js`.');

fs.writeFileSync(path.join(__dirname, '../docs/recipe-book.md'), L.join('\n') + '\n');
console.log('Wrote docs/recipe-book.md');
