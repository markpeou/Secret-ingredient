// Calibrates the scoring against simulated players and writes js/data/calibration.js.
//   node scripts/calibrate.js
//
// 1. SPICE_NORMS: each spice's typical score (mean, spread) across players, so a
//    spice that is easy to score highly doesn't dominate every result.
// 2. DISH_BIAS: small per-dish offsets so every dish turns up for some players
//    and none takes over. Offsets are capped so answers still decide the dish.
const fs = require('fs');
const path = require('path');
const SI = require('../tests/load');
const { players } = require('../tests/players');

delete SI.SPICE_NORMS; delete SI.DISH_BIAS;
const sample = players(8000, 2024).map((a) => SI.engine.scoreSpices(SI.engine.buildProfile(a)));

const norms = {};
SI.SPICES.forEach((sp) => {
  const vals = sample.map((sc) => sc.find((x) => x.spice.id === sp.id).score);
  const mean = vals.reduce((a, b) => a + b, 0) / vals.length;
  const sd = Math.sqrt(vals.reduce((a, b) => a + (b - mean) ** 2, 0) / vals.length);
  norms[sp.id] = { mean: +mean.toFixed(4), sd: +sd.toFixed(4) };
});
SI.SPICE_NORMS = norms;
const centred = sample.map((sc) => SI.engine.centre(sc));

const CAP = 0.6, target = 1 / SI.DISHES.length;
const bias = Object.fromEntries(SI.DISHES.map((d) => [d.id, 0]));
for (let it = 0; it < 120; it++) {
  const counts = Object.fromEntries(SI.DISHES.map((d) => [d.id, 0]));
  centred.forEach((c) => { counts[SI.engine.chooseDish(c, bias).dish.id]++; });
  SI.DISHES.forEach((d) => {
    const f = Math.max(counts[d.id] / centred.length, 1e-4);
    bias[d.id] = Math.max(-CAP, Math.min(CAP, bias[d.id] + 0.08 * Math.log(target / f)));
  });
}
Object.keys(bias).forEach((k) => { bias[k] = +bias[k].toFixed(3); });

const out = `/* Generated by scripts/calibrate.js — do not edit by hand. Rerun after changing questions, spices or dishes. */
(function (SI) {
  SI.SPICE_NORMS = ${JSON.stringify(norms)};
  SI.DISH_BIAS = ${JSON.stringify(bias)};
})(globalThis.SI = globalThis.SI || {});
`;
fs.writeFileSync(path.join(__dirname, '../js/data/calibration.js'), out);
const vals = Object.values(bias);
console.log('Wrote js/data/calibration.js. Dish offsets range', Math.min(...vals), 'to', Math.max(...vals));
